const herbsGrid =
    document.getElementById("herbsGrid");

const searchInput =
    document.getElementById("searchInput");

const resultsCount =
    document.getElementById("resultsCount");

const emptyState =
    document.getElementById("emptyState");

const clearSearch =
    document.getElementById("clearSearch");

const menuButton =
    document.getElementById("menuButton");



let currentType = "todos";



/* =====================================================
   NORMALIZAR TEXTO
===================================================== */

function normalizeText(text) {

    return text
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "")
        .toLowerCase();

}



/* =====================================================
   RENDERIZAR ERVAS
===================================================== */

function renderHerbs() {

    const search =
        normalizeText(
            searchInput.value.trim()
        );


    const filtered =
        herbs.filter(herb => {

            const matchesType =
                currentType === "todos" ||
                herb.tipo === currentType;


            const searchableText = normalizeText(
                [
                    herb.nome,
                    herb.funcao,
                    herb.orixa,
                    herb.uso
                ].join(" ")
            );


            const matchesSearch =
                searchableText.includes(search);


            return (
                matchesType &&
                matchesSearch
            );

        });


    herbsGrid.innerHTML = "";


    filtered.forEach(herb => {

        const card =
            document.createElement("article");


        card.className =
            "herb-card";


        card.innerHTML = `

            <div class="herb-image">

                <img
                    src="${herb.imagem}"
                    alt="${herb.nome}"
                    loading="lazy"
                    onerror="this.src='assets/ervas/placeholder.jpg'"
                >

            </div>


            <div class="herb-content">

                <div class="herb-top">

                    <h3 class="herb-name">
                        ${herb.nome}
                    </h3>

                    <span class="badge">
                        ${herb.tipoLabel}
                    </span>

                </div>


                <p class="herb-function">
                    ${herb.funcao}
                </p>


                <div class="herb-info">

                    <div class="info">

                        <label>
                            Orixá
                        </label>

                        <span>
                            ${herb.orixa}
                        </span>

                    </div>


                    <div class="info">

                        <label>
                            Uso
                        </label>

                        <span>
                            ${herb.uso}
                        </span>

                    </div>

                </div>

            </div>

        `;


        herbsGrid.appendChild(card);

    });


    const total =
        filtered.length;


    resultsCount.textContent =
        `${total} ${total === 1 ? "erva" : "ervas"}`;


    emptyState.style.display =
        total === 0
            ? "block"
            : "none";

}



/* =====================================================
   BUSCA
===================================================== */

searchInput.addEventListener(
    "input",
    () => {

        clearSearch.classList.toggle(
            "visible",
            searchInput.value.length > 0
        );


        renderHerbs();

    }
);



/* =====================================================
   LIMPAR BUSCA
===================================================== */

clearSearch.addEventListener(
    "click",
    () => {

        searchInput.value = "";

        clearSearch.classList.remove(
            "visible"
        );

        searchInput.focus();

        renderHerbs();

    }
);



/* =====================================================
   FILTROS
===================================================== */

document
    .querySelectorAll(".type-filter")
    .forEach(button => {

        button.addEventListener(
            "click",
            () => {

                document
                    .querySelectorAll(
                        ".type-filter"
                    )
                    .forEach(btn => {

                        btn.classList.remove(
                            "active"
                        );

                    });


                button.classList.add(
                    "active"
                );


                currentType =
                    button.dataset.type;


                renderHerbs();


                document
                    .getElementById("ervas")
                    .scrollIntoView({
                        behavior: "smooth",
                        block: "start"
                    });

            }
        );

    });



/* =====================================================
   MENU MOBILE
===================================================== */

menuButton.addEventListener(
    "click",
    () => {

        const nav =
            document.querySelector(".nav");


        nav.classList.toggle(
            "mobile-open"
        );

    }
);



/* =====================================================
   INICIALIZAÇÃO
===================================================== */

renderHerbs();
